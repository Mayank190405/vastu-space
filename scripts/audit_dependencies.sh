#!/usr/bin/env bash
set -e

OUTPUT_FILE="DEPENDENCY_INVENTORY.md"

echo "# DEPENDENCY INVENTORY" > $OUTPUT_FILE
echo "**Auto-generated by audit_dependencies.sh**" >> $OUTPUT_FILE
echo "" >> $OUTPUT_FILE

echo "## 1. Backend (Go)" >> $OUTPUT_FILE
if [ -f "backend/go.mod" ]; then
    echo "✅ \`backend/go.mod\` found." >> $OUTPUT_FILE
    echo "\`\`\`" >> $OUTPUT_FILE
    cat backend/go.mod >> $OUTPUT_FILE
    echo "\`\`\`" >> $OUTPUT_FILE
else
    echo "❌ \`backend/go.mod\` NOT FOUND." >> $OUTPUT_FILE
fi
echo "" >> $OUTPUT_FILE

echo "## 2. Python Workers" >> $OUTPUT_FILE
PYTHON_REQS=""
for f in "requirements.txt" "requirements.lock" "pyproject.toml" "poetry.lock" "environment.yml" "conda.yaml"; do
    if [ -f "$f" ]; then PYTHON_REQS="$f"; break; fi
    if [ -f "backend/$f" ]; then PYTHON_REQS="backend/$f"; break; fi
    if [ -f "backend/workers/$f" ]; then PYTHON_REQS="backend/workers/$f"; break; fi
done

if [ -n "$PYTHON_REQS" ]; then
    echo "✅ Python dependencies found in \`$PYTHON_REQS\`." >> $OUTPUT_FILE
    echo "\`\`\`" >> $OUTPUT_FILE
    cat "$PYTHON_REQS" >> $OUTPUT_FILE
    echo "\`\`\`" >> $OUTPUT_FILE
else
    echo "❌ NO Python dependency file (requirements.txt, conda.yaml, etc) found." >> $OUTPUT_FILE
    echo "STATUS: **NOT EVIDENCED**" >> $OUTPUT_FILE
fi
echo "" >> $OUTPUT_FILE

echo "## 3. C++ Workers" >> $OUTPUT_FILE
if [ -f "backend/workers/CMakeLists.txt" ] || [ -f "backend/CMakeLists.txt" ] || [ -f "CMakeLists.txt" ]; then
    echo "✅ CMakeLists.txt found." >> $OUTPUT_FILE
else
    echo "❌ NO CMakeLists.txt or C++ build scripts found." >> $OUTPUT_FILE
    echo "STATUS: **NOT EVIDENCED**" >> $OUTPUT_FILE
fi
echo "" >> $OUTPUT_FILE

echo "## 4. Android (Kotlin)" >> $OUTPUT_FILE
if [ -f "android/app/build.gradle.kts" ]; then
    echo "✅ \`android/app/build.gradle.kts\` found." >> $OUTPUT_FILE
    echo "\`\`\`kotlin" >> $OUTPUT_FILE
    cat android/app/build.gradle.kts | grep -E "compileSdk|minSdk|targetSdk|jvmTarget|versionCode|versionName|implementation|ksp|camera|room|compose|kotlinCompilerExtensionVersion" >> $OUTPUT_FILE
    echo "\`\`\`" >> $OUTPUT_FILE
else
    echo "❌ \`android/app/build.gradle.kts\` NOT FOUND." >> $OUTPUT_FILE
fi
echo "" >> $OUTPUT_FILE

echo "## 5. iOS (Swift)" >> $OUTPUT_FILE
if [ -f "ios/Package.swift" ]; then
    echo "✅ \`ios/Package.swift\` found." >> $OUTPUT_FILE
    echo "\`\`\`swift" >> $OUTPUT_FILE
    cat ios/Package.swift >> $OUTPUT_FILE
    echo "\`\`\`" >> $OUTPUT_FILE
else
    echo "❌ \`ios/Package.swift\` NOT FOUND." >> $OUTPUT_FILE
fi
echo "" >> $OUTPUT_FILE

echo "## 6. Frontend" >> $OUTPUT_FILE
if [ -f "package.json" ]; then
    echo "✅ \`package.json\` found." >> $OUTPUT_FILE
    echo "\`\`\`json" >> $OUTPUT_FILE
    grep -A 20 '"dependencies"' package.json >> $OUTPUT_FILE || true
    echo "\`\`\`" >> $OUTPUT_FILE
else
    echo "❌ \`package.json\` NOT FOUND." >> $OUTPUT_FILE
fi
echo "" >> $OUTPUT_FILE

echo "Inventory complete. Results written to $OUTPUT_FILE."
